// The token radar's model: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and may add
// pre-token protocols below the watchlist floor: the early rows the radar exists to find. A protocol is
// pre-token when its index entry records no token (no market cap, no CoinGecko id, no symbol); the
// snapshot's live-token protocols are kept apart and shown as the market's own values, never mixed into
// the ranked board.
//
// Implied value follows only from the snapshot's own figures, fitted on the 128 issued-token
// protocols that carry a positive market cap:
//
//   log(mcap) = 6.9646 + 0.5223 x log(TVL)          (OLS, n = 128, R^2 = 0.194, residual SD 2.077 log units)
//   base       = exp(6.9646 + 0.5223 x ln(tvl_usd))
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x 0.5
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   implied    = max(1, round(base x growthMult x maturity))
//   low/high   = implied x exp(-/+ 1.2816 x 2.077)        (the 80% interval from the fit's residuals)
//
// The fit is weak on purpose and the dashboard says so: R^2 0.194 means TVL alone explains about a
// fifth of the variation in market caps, and the 80% interval spans roughly 0.07x to 14.3x the centre
// estimate. What the fit buys over the starter's flat TVL x 0.25 is calibration: on the time-split
// holdout (trained on the 75 protocols listed before 2025-06-01, tested on the 20 listed after) the
// fitted curve scores RMSE(log) 2.52 with 30% of predictions within 2x, against the starter's 2.87
// and 25%. A per-category intercept was tried on the same split and scored worse (RMSE(log) 2.66),
// so the board uses one global curve and no category is special-cased. No protocol name is ever
// special-cased: the same function scores every row.

